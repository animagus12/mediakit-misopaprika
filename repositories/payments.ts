// The payment ledger: one record per sum of money that arrived against a deal,
// a usage renewal or a standalone invoice.
//
// Types and the pure core only, and deliberately no "server-only": the
// campaign and invoice mappers (./campaigns, ./invoices) settle every target
// as they read it, and forms validate against the same rules the server does.
// Storage lives in ./paymentRecords.server and ./payments.writer.server.
//
// Status is derived, never stored here: a target is paid, partly paid,
// pending or not tracked because of the entries against it. The legacy
// payment fields a deal, renewal or invoice already carries (paymentStatus,
// paidDate, an invoice's advance) are read as "virtual" entries for as long as
// the target has no stored entry of its own, so a book written before the
// ledger reads exactly as it did. See lib/payments.ts for the joins.
//
// Runtime imports are limited to lib/money, lib/payers, lib/financialYear,
// lib/day and lib/tds; ./campaigns is imported for types only. ./campaigns
// calls into this file from toCampaign, so a runtime import back would be a
// cycle.

import { roundMoney, sumMoney } from "@/lib/money";
import { toFinancialDayKey } from "@/lib/financialYear";
import { toPayer, toPaymentMethod, type Payer, type PaymentMethod } from "@/lib/payers";
import { resolveTds } from "@/lib/tds";
import type { CampaignPaymentStatus } from "./campaigns";

export type PaymentTarget =
  | { kind: "deal"; campaignId: string }
  | { kind: "renewal"; campaignId: string; renewalId: string }
  // Standalone invoices only: an invoice that bills a deal or a renewal never
  // holds entries of its own (see validatePayment in lib/payments.ts).
  | { kind: "invoice"; invoiceId: string };

/** "legacy" marks a record materialised from a virtual entry. */
export type PaymentOrigin = "recorded" | "legacy";

export interface PaymentRecord {
  /** crypto.randomUUID(), generated by the client once per sheet open or click. */
  id: string;
  target: PaymentTarget;
  /** yyyy-mm-dd IST day key; "" only when origin is "legacy". */
  date: string;
  /** What this settles against the amount owed, TDS included. > 0, at most 2 decimals. */
  gross: number;
  tds: number;
  bankFee: number;
  /** Whose account the money landed in; null only when origin is "legacy". */
  receivedInto: Payer | null;
  method: PaymentMethod | null;
  /** UTR, cheque or transaction id, trimmed, "" when none. */
  reference: string;
  note: string;
  origin: PaymentOrigin;
  createdAt: string; // ISO
  updatedAt: string; // ISO
}

/** What a form or a quick action submits. */
export interface PaymentInput {
  id: string;
  target: PaymentTarget;
  date: string;
  gross: number;
  tds: number;
  bankFee: number;
  receivedInto: Payer;
  method: PaymentMethod | null;
  reference: string;
  note: string;
}

export type SettlementStatus = "paid" | "partial" | "pending" | "unknown";
export type LegacyKind = "status" | "advance";

export interface LedgerEntry extends PaymentRecord {
  net: number;
  source: "stored" | "virtual";
  /** Which legacy field a virtual entry stands for; null on stored entries. */
  legacyKind: LegacyKind | null;
  /** `date`, else the target's fallback day; "" when neither parses. */
  bucketDate: string;
  /** A virtual entry whose TDS was estimated from the rate. */
  tdsEstimated: boolean;
}

export interface Settlement {
  target: PaymentTarget;
  owed: number;
  settled: number;
  tds: number;
  fee: number;
  net: number;
  remaining: number;
  overpaid: number;
  status: SettlementStatus;
  /** Day the running gross first reached `owed`; "" if not paid or that entry is undated. */
  paidOn: string;
  /** Latest dated entry, or "". */
  lastPaidOn: string;
  method: PaymentMethod | "Multiple" | "";
  /** Undated first, then by date, then by createdAt. */
  entries: LedgerEntry[];
  hasStored: boolean;
}

export const PAYMENTS_SEED_KEY = "payments";
export const LEGACY_ID_PREFIX = "legacy:";

export const PAYMENT_REFERENCE_MAX = 80;
export const PAYMENT_NOTE_MAX = 500;

export function paymentTargetKey(target: PaymentTarget): string {
  switch (target.kind) {
    case "deal":
      return `deal:${target.campaignId}`;
    case "renewal":
      return `renewal:${target.campaignId}:${target.renewalId}`;
    case "invoice":
      return `invoice:${target.invoiceId}`;
  }
}

export function samePaymentTarget(a: PaymentTarget, b: PaymentTarget): boolean {
  return paymentTargetKey(a) === paymentTargetKey(b);
}

/** What actually landed in the account: gross less TDS and bank charges. Never stored. */
export function paymentNet(payment: Pick<PaymentRecord, "gross" | "tds" | "bankFee">): number {
  return roundMoney(payment.gross - payment.tds - payment.bankFee);
}

function trimmedId(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

/** A stored or submitted target, or null when it is not one of the three shapes. */
export function toPaymentTarget(raw: unknown): PaymentTarget | null {
  if (typeof raw !== "object" || raw === null) return null;
  const candidate = raw as Record<string, unknown>;
  const campaignId = trimmedId(candidate.campaignId);
  switch (candidate.kind) {
    case "deal":
      return campaignId ? { kind: "deal", campaignId } : null;
    case "renewal": {
      const renewalId = trimmedId(candidate.renewalId);
      return campaignId && renewalId ? { kind: "renewal", campaignId, renewalId } : null;
    }
    case "invoice": {
      const invoiceId = trimmedId(candidate.invoiceId);
      return invoiceId ? { kind: "invoice", invoiceId } : null;
    }
    default:
      return null;
  }
}

function amount(value: unknown): number {
  return roundMoney(Math.max(0, Number(value) || 0));
}

function text(value: unknown, max: number): string {
  return typeof value === "string" ? value.trim().slice(0, max) : "";
}

/**
 * A record read back out of storage, coerced whole, or null when it cannot be
 * one (no usable target, or nothing settled). Same coerce-on-read treatment
 * every other store gets, so a hand-edited or older row never reaches past
 * the repository half-formed.
 */
export function toPaymentRecord(raw: unknown): PaymentRecord | null {
  if (typeof raw !== "object" || raw === null) return null;
  const candidate = raw as Record<string, unknown>;
  const id = trimmedId(candidate.id);
  const target = toPaymentTarget(candidate.target);
  const gross = amount(candidate.gross);
  if (!id || !target || gross <= 0) return null;
  return {
    id,
    target,
    date: toFinancialDayKey(String(candidate.date ?? "")) ?? "",
    gross,
    tds: amount(candidate.tds),
    bankFee: amount(candidate.bankFee),
    receivedInto: toPayer(candidate.receivedInto) ?? null,
    method: toPaymentMethod(candidate.method) ?? null,
    reference: text(candidate.reference, PAYMENT_REFERENCE_MAX),
    note: text(candidate.note, PAYMENT_NOTE_MAX),
    origin: candidate.origin === "legacy" ? "legacy" : "recorded",
    createdAt: typeof candidate.createdAt === "string" ? candidate.createdAt : "",
    updatedAt: typeof candidate.updatedAt === "string" ? candidate.updatedAt : "",
  };
}

/** "legacy:status:deal:MSP-MC0007", "legacy:advance:renewal:MSP-MC0010:R0002". */
export function virtualEntryId(kind: LegacyKind, target: PaymentTarget): string {
  return `${LEGACY_ID_PREFIX}${kind}:${paymentTargetKey(target)}`;
}

export function isVirtualEntryId(id: string): boolean {
  return id.startsWith(LEGACY_ID_PREFIX);
}

/** The legacy field and target a virtual entry's id names, or null for any other id. */
export function parseVirtualEntryId(id: string): { kind: LegacyKind; target: PaymentTarget } | null {
  if (!isVirtualEntryId(id)) return null;
  const [kind, targetKind, first, second, ...rest] = id.slice(LEGACY_ID_PREFIX.length).split(":");
  if ((kind !== "status" && kind !== "advance") || rest.length > 0 || !first) return null;
  if (targetKind === "deal" && second === undefined) return { kind, target: { kind: "deal", campaignId: first } };
  if (targetKind === "invoice" && second === undefined) return { kind, target: { kind: "invoice", invoiceId: first } };
  if (targetKind === "renewal" && second) {
    return { kind, target: { kind: "renewal", campaignId: first, renewalId: second } };
  }
  return null;
}

/** A stored record as the ledger reads it. `bucketFallback` is the target's day key. */
export function toLedgerEntry(record: PaymentRecord, bucketFallback: string): LedgerEntry {
  return {
    ...record,
    net: paymentNet(record),
    source: "stored",
    legacyKind: null,
    bucketDate: record.date || bucketFallback,
    tdsEstimated: false,
  };
}

/** The day key a DD/MM/YYYY or yyyy-mm-dd date stands for, "" when neither. */
export function ledgerDayKey(date: string | null | undefined): string {
  return toFinancialDayKey(date ?? "") ?? "";
}

/** The first of `dates` that parses, as a day key; "" when none does. */
export function firstDayKey(...dates: (string | null | undefined)[]): string {
  for (const date of dates) {
    const key = ledgerDayKey(date);
    if (key) return key;
  }
  return "";
}

interface LegacyEntryFields {
  gross: number;
  /** DD/MM/YYYY or yyyy-mm-dd; "" when not recorded. */
  paidDate: string;
  method: string;
  tdsRate: number | null;
  tdsAmount: number | null;
  /** Day key the entry is filed under while it has no date of its own. */
  bucketFallback: string;
}

function virtualEntry(
  kind: LegacyKind,
  target: PaymentTarget,
  fields: LegacyEntryFields
): LedgerEntry {
  const gross = roundMoney(fields.gross);
  const tds = kind === "status" ? resolveTds(gross, fields.tdsRate, fields.tdsAmount) : null;
  const date = kind === "status" ? ledgerDayKey(fields.paidDate) : "";
  const record: PaymentRecord = {
    id: virtualEntryId(kind, target),
    target,
    date,
    gross,
    tds: roundMoney(tds?.amount ?? 0),
    bankFee: 0,
    receivedInto: null,
    method: kind === "status" ? toPaymentMethod(fields.method) ?? null : null,
    reference: "",
    note: "",
    origin: "legacy",
    createdAt: "",
    updatedAt: "",
  };
  return {
    ...record,
    net: paymentNet(record),
    source: "virtual",
    legacyKind: kind,
    bucketDate: date || fields.bucketFallback,
    tdsEstimated: tds?.estimated ?? false,
  };
}

/**
 * The virtual entry a stored "received" stands for: the whole of what is owed,
 * dated by the stored paid date, carrying the target's TDS pair.
 */
export function legacyStatusEntry(target: PaymentTarget, fields: LegacyEntryFields): LedgerEntry {
  return virtualEntry("status", target, fields);
}

/** The virtual entry an invoice's advance stands for, capped at what is owed. Never dated, no TDS. */
export function legacyAdvanceEntry(
  target: PaymentTarget,
  advance: number,
  owed: number,
  bucketFallback: string
): LedgerEntry {
  return virtualEntry("advance", target, {
    gross: Math.min(roundMoney(advance), owed),
    paidDate: "",
    method: "",
    tdsRate: null,
    tdsAmount: null,
    bucketFallback,
  });
}

function compareEntries(a: LedgerEntry, b: LedgerEntry): number {
  if (a.date === "" && b.date !== "") return -1;
  if (b.date === "" && a.date !== "") return 1;
  return a.date.localeCompare(b.date) || a.createdAt.localeCompare(b.createdAt);
}

function settledMethod(entries: LedgerEntry[]): Settlement["method"] {
  const methods = new Set<PaymentMethod>();
  let last: PaymentMethod | null = null;
  for (const entry of entries) {
    if (!entry.method) continue;
    methods.add(entry.method);
    last = entry.method;
  }
  if (methods.size > 1) return "Multiple";
  return last ?? "";
}

/**
 * Everything the ledger says about one target.
 *
 * `stored` is the target's stored payment status, which only decides between
 * "unknown" and "pending" while nothing has been received: whether anyone is
 * tracking the money is not something entries can say.
 */
export function settle(
  target: PaymentTarget,
  owed: number,
  entries: LedgerEntry[],
  stored: CampaignPaymentStatus
): Settlement {
  const sorted = [...entries].sort(compareEntries);
  const owedAmount = roundMoney(owed);
  const settled = sumMoney(sorted.map((entry) => entry.gross));
  const tds = sumMoney(sorted.map((entry) => entry.tds));
  const fee = sumMoney(sorted.map((entry) => entry.bankFee));

  let status: SettlementStatus;
  if (sorted.length === 0) status = owedAmount <= 0 || stored === "unknown" ? "unknown" : "pending";
  else if (roundMoney(owedAmount - settled) <= 0) status = "paid";
  else if (settled > 0) status = "partial";
  else status = "pending";

  let paidOn = "";
  if (status === "paid") {
    let running = 0;
    for (const entry of sorted) {
      running = roundMoney(running + entry.gross);
      if (running >= owedAmount) {
        paidOn = entry.date;
        break;
      }
    }
  }

  const lastPaidOn = sorted.reduce((latest, entry) => (entry.date > latest ? entry.date : latest), "");

  return {
    target,
    owed: owedAmount,
    settled,
    tds,
    fee,
    net: roundMoney(settled - tds - fee),
    remaining: Math.max(0, roundMoney(owedAmount - settled)),
    overpaid: Math.max(0, roundMoney(settled - owedAmount)),
    status,
    paidOn,
    lastPaidOn,
    method: settledMethod(sorted),
    entries: sorted,
    hasStored: sorted.some((entry) => entry.source === "stored"),
  };
}

/**
 * The payment status a target reads as. While it has no stored entry this is
 * the stored value exactly (the identity that keeps a pre-ledger book
 * unchanged); once it has one, the ledger decides.
 */
export function projectPaymentStatus(
  settlement: Settlement,
  stored: CampaignPaymentStatus
): CampaignPaymentStatus {
  if (!settlement.hasStored) return stored;
  return settlement.status === "paid" ? "received" : "pending";
}

/**
 * Whether a deal's barter half has been delivered, apart from its cash.
 *
 * Barter-only deals use the payment status for the parcel, so it is the
 * answer. A Barter+Paid deal carries one status for both halves until it has
 * an explicit barterStatus: received (or cash paid in full) reads as
 * delivered, as it always has.
 */
export function deriveBarterState(
  hasCash: boolean,
  hasBarter: boolean,
  storedPaymentStatus: CampaignPaymentStatus,
  barterStatus: CampaignPaymentStatus | undefined,
  cash: Settlement | null
): CampaignPaymentStatus | null {
  if (!hasBarter) return null;
  if (!hasCash) return storedPaymentStatus;
  if (barterStatus !== undefined) return barterStatus;
  if (storedPaymentStatus === "received" || cash?.status === "paid") return "received";
  return storedPaymentStatus;
}
